from src.day02 import add, mul


def test_add():
    assert add([1, 9, 10, 3, 2, 3, 11, 0, 99, 30, 40, 50], 0) == [
        1,
        9,
        10,
        70,
        2,
        3,
        11,
        0,
        99,
        30,
        40,
        50,
    ]

def test_mul():
    assert mul([
        1,
        9,
        10,
        70,
        2,
        3,
        11,
        0,
        99,
        30,
        40,
        50,
    ], 4) == [
        3500,
        9,
        10,
        70,
        2,
        3,
        11,
        0,
        99,
        30,
        40,
        50,
    ]